# =====================================================================
# 典型90 - 010: Score Sum Queries  (リファクタ版)
# ---------------------------------------------------------------------
# 元コード (010.py) からのリファクタ。アルゴリズム自体は同じで、
# 「1 組の累積和」と「2 組の累積和」をそれぞれ作ってクエリに O(1) で答える。
#
# 元コードで「書きにくかった」と感じた箇所への対策:
#   (A) 2 次元配列の scores[i][0] / scores[i][1] が読みづらい
#       → 役割ごとに 1 次元配列 (classes / points) に分ける
#   (B) L == 1 のときだけ if 文で特別扱いしていた
#       → 累積和の長さを N ではなく N+1 にして、先頭に「合計 0」のダミーを置く。
#         そうすると sum[R] - sum[L-1] という 1 本の式で全クエリを処理できる。
#   (C) 毎クエリ print していた
#       → 答えをリストに溜めて最後に "\n".join で 1 回だけ出力。
#         Q が大きいとき (10^5 程度) これだけで体感が変わる。
# =====================================================================


# ========================================================
# 1. 入力: N と各生徒の (組, 点数)
# ========================================================
N = int(input())

# Python で「2 次元配列 [[c1, p1], [c2, p2], ...]」を作って
# scores[i][0] / scores[i][1] とアクセスするより、
# 役割ごとに 1 次元配列を 2 本用意する方が、後で読み返したときに意味がわかりやすい。
classes = [0] * N   # classes[i] : 学籍番号 i+1 番の生徒の組 (1 か 2)
points  = [0] * N   # points[i]  : 学籍番号 i+1 番の生徒の点数

for i in range(N):
    # input()             … 1 行を文字列で受け取る   例: "1 72"
    # .split()            … 空白区切りでリスト化     例: ["1", "72"]
    # map(int, ...)       … 各要素を int に変換 (まだリストではなくイテレータ)
    # c, p = ...          … 左辺の変数の数だけ順に取り出して代入 (アンパック代入)
    #
    # アンパック代入を覚えると、scores[i][0] みたいな添字アクセスを書かずに
    # 「c, p」という意味ある名前で扱えるようになる。競プロ Python の超頻出テクニック。
    c, p = map(int, input().split())
    classes[i] = c
    points[i]  = p

Q = int(input())


# ========================================================
# 2. 累積和の構築 (★ここが今回のリファクタの肝)
# ========================================================
# 累積和の定義をきっちり日本語で書いておく:
#   sum1[i] = 「学籍番号 1 番から i 番までの生徒のうち、1 組の点数の合計」
#   sum2[i] = 「学籍番号 1 番から i 番までの生徒のうち、2 組の点数の合計」
#
# 重要: i = 0 は「誰も含まれない状態」と定義する。当然合計は 0。
# これがダミー要素 sum[0] = 0 の正体で、長さを N+1 にする理由。
#
# この定義をしておくと、学籍番号 L 番〜 R 番の合計は
#       sum1[R] - sum1[L - 1]
# という 1 本の式で書ける。
# L = 1 のときも sum1[0] = 0 が入っているので「引いても変わらない」ので
# わざわざ if で分岐しなくていい。← 元コードの痛かった部分が消える！
sum1 = [0] * (N + 1)
sum2 = [0] * (N + 1)

for i in range(N):
    # まず「1 個前まで」の累積値をそのまま引き継ぐ
    sum1[i + 1] = sum1[i]
    sum2[i + 1] = sum2[i]

    # その上で、今見ている生徒 (= 学籍番号 i+1 番) の点数を、該当する組の側だけに足す
    if classes[i] == 1:
        sum1[i + 1] += points[i]
    else:
        sum2[i + 1] += points[i]


# ========================================================
# 3. クエリ処理
# ========================================================
# 競プロ Python の鉄則:「ループの中で print を呼ばない」。
# print は 1 回ごとに flush などのコストがかかるので、
# Q が 10 万回くらいになるとそれだけで TLE することがある。
# 答えはいったんリストにためて、最後にまとめて 1 回だけ出力する。
ans = []
for _ in range(Q):
    L, R = map(int, input().split())

    # L 番〜 R 番の中で 1 組の点数合計
    a = sum1[R] - sum1[L - 1]
    # L 番〜 R 番の中で 2 組の点数合計
    b = sum2[R] - sum2[L - 1]

    # f-string: 変数を文字列に埋め込む書き方。"63 261" のような形に整形される。
    ans.append(f"{a} {b}")

# "\n".join(リスト) … リストの各要素を改行で連結した 1 本の文字列を作る。
# それを print に渡すと、I/O 呼び出しは 1 回で済むので速い。
print("\n".join(ans))
